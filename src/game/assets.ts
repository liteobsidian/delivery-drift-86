import midriseAssetSrc from "../assets/props/midrise/asset.js?raw";
import midriseOrientSrc from "../assets/props/midrise/orientation.js?raw";
import midriseDataUrl from "../assets/props/midrise/data.json.gz.b64?url";
import midrisePackUrl from "../assets/props/midrise/pack-1.bin.gz.b64?url";
import { loadGlbModel, type GlbModel } from "./glb";

// AI-generated car bodies (Tripo), one GLB per car — see src/assets/vehicles2/
import ae86Url from "../assets/vehicles2/ae86.glb?url";
import supraUrl from "../assets/vehicles2/supra.glb?url";
import silviaUrl from "../assets/vehicles2/silvia.glb?url";
import rx7Url from "../assets/vehicles2/rx7.glb?url";
import r34Url from "../assets/vehicles2/r34.glb?url";
import nsxUrl from "../assets/vehicles2/nsx.glb?url";
import evoUrl from "../assets/vehicles2/evo.glb?url";
import tHatchUrl from "../assets/vehicles2/t_hatch.glb?url";
import tSedanUrl from "../assets/vehicles2/t_sedan.glb?url";
import tCoupeUrl from "../assets/vehicles2/t_coupe.glb?url";
import policeGlbUrl from "../assets/vehicles2/police.glb?url";

export interface LoadedModel {
  /** wrapper group: metre scale, sits on y=0, nose faces local -z */
  root: THREE.Group;
  /** bounding size after normalization */
  size: THREE.Vector3;
}

export interface GameAssets {
  /** civilian cars for traffic */
  traffic: LoadedModel[];
  police: LoadedModel;
  midrise: LoadedModel;
  /** detailed AI-generated hero-car bodies, keyed by car id */
  hero: Partial<Record<HeroModelKey, LoadedModel>>;
}

export type HeroModelKey = "ae86" | "supra" | "silvia" | "rx7" | "r34" | "nsx" | "evo";

type CreateAsset = (
  three: unknown,
  opts: { states: string; sharedResources: boolean }
) => Promise<THREE.Group & { setState: (name: string) => Promise<void> }>;

/** Strip ESM import/export syntax so module sources can run inside an IIFE. */
function stripModuleSyntax(src: string): string {
  return src
    .split("\n")
    .filter(
      (l) =>
        !/^import\s/.test(l) &&
        !/^\s*export\s*\{[^}]*\};?\s*$/.test(l) &&
        !/^\s*export\s+default\s+\w+;?\s*$/.test(l)
    )
    .join("\n")
    .replace(/^export\s+(const|let|var|async function|function|class)/gm, "$1");
}

/** One fully self-contained asset module (own loader copy => own manifest cache). */
function assetBlock(...parts: string[]): string {
  const body = parts
    .map(stripModuleSyntax)
    .join("\n")
    // blob: URLs cannot be bases for relative URL resolution; the fetch shim
    // keys payloads on the filename suffix, so any absolute base works
    .replace(/import\.meta\.url/g, JSON.stringify("https://assets.invalid/pack/"));
  return `(() => {\n${body}\nreturn createAsset;\n})()`;
}

const moduleSource = `// generated by src/game/assets.ts — self-contained packed asset modules
const assets = {
  midrise: ${assetBlock(midriseOrientSrc, loaderSrc, midriseAssetSrc)},
};
export { assets };
`;

// gzip payloads as base64 text, decoded by the fetch shim per active asset
const B64_URLS: Record<string, { "data.json.gz": string; "pack-1.bin.gz": string }> = {
  midrise: { "data.json.gz": midriseDataUrl, "pack-1.bin.gz": midrisePackUrl },
};

/**
 * AI-generated hero cars (Tripo GLBs). noseRotY aligns each model's nose to
 * local -z (verified from in-engine renders); wheels are carved out of the
 * merged mesh at load time so they spin/steer.
 */
const HERO_GLBS: Record<HeroModelKey, { url: string; noseRotY: number; len: number }> = {
  ae86: { url: ae86Url, noseRotY: Math.PI / 2, len: 4.2 },
  supra: { url: supraUrl, noseRotY: -Math.PI / 2, len: 4.5 },
  silvia: { url: silviaUrl, noseRotY: Math.PI / 2, len: 4.45 },
  rx7: { url: rx7Url, noseRotY: Math.PI / 2, len: 4.4 },
  r34: { url: r34Url, noseRotY: Math.PI, len: 4.6 },
  nsx: { url: nsxUrl, noseRotY: Math.PI / 2, len: 4.4 },
  evo: { url: evoUrl, noseRotY: Math.PI / 2, len: 4.5 },
};

const TRAFFIC_GLBS: { url: string; noseRotY: number; len: number }[] = [
  { url: tHatchUrl, noseRotY: Math.PI, len: 4.15 },
  { url: tSedanUrl, noseRotY: Math.PI, len: 4.6 },
  { url: tCoupeUrl, noseRotY: Math.PI, len: 4.45 },
];

/**
 * The packed payloads ship as base64 text (the publishing channel is
 * text-friendly). The loaders fetch `data.json.gz` / `pack-1.bin.gz`
 * relative to their base URL; this shim serves the decoded gzip bytes for
 * whichever asset is currently loading.
 */
let activeAsset: string | null = null;
let b64ShimInstalled = false;
function installB64FetchShim(): void {
  if (b64ShimInstalled) return;
  b64ShimInstalled = true;
  const origFetch = window.fetch.bind(window);
  window.fetch = (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url =
      typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
    const m = /(data\.json\.gz|pack-1\.bin\.gz)([?#].*)?$/.exec(url);
    if (activeAsset && m && B64_URLS[activeAsset]) {
      const r = await origFetch(B64_URLS[activeAsset][m[1] as "data.json.gz"], init);
      if (r.ok) {
        const text = (await r.text()).trim();
        const bytes = Uint8Array.from(atob(text), (c) => c.charCodeAt(0));
        return new Response(bytes, {
          status: 200,
          headers: { "content-type": "application/octet-stream" },
        });
      }
    }
    return origFetch(input, init);
  }) as typeof window.fetch;
}

let modulePromise: Promise<{ assets: Record<string, CreateAsset> }> | null = null;
function loadAssetModule(): Promise<{ assets: Record<string, CreateAsset> }> {
  if (!modulePromise) {
    installB64FetchShim();
    const blob = new Blob([moduleSource], { type: "text/javascript" });
    modulePromise = import(/* @vite-ignore */ URL.createObjectURL(blob));
  }
  return modulePromise;
}

/**
 * Loads one packed asset and normalizes it: rotY aligns the nose to local -z,
 * normalize() picks the uniform scale, and the model is grounded so its bbox
 * min.y sits at 0.
 */
async function loadModel(
  mod: Record<string, CreateAsset>,
  key: string,
  rotY: number,
  normalize: (size: THREE.Vector3) => number
): Promise<LoadedModel> {
  // the shim keys payloads on the asset being loaded; load sequentially
  activeAsset = key;
  try {
    const inner = await mod[key](THREE, {
      states: "lazy",
      sharedResources: true,
    });
    // lazy states load geometry only on setState — without this the bounds
    // are empty and normalization would compute a gigantic scale
    await inner.setState(ASSET_STATES[key]);
    // showroom materials use transmission, which forces a full extra render pass
    // in three.js — way too costly for a traffic fleet. Glass stays glass.
    inner.traverse((o) => {
      const mesh = o as THREE.Mesh;
      const mats = Array.isArray(mesh.material)
        ? mesh.material
        : [mesh.material];
      for (const m of mats) {
        const pm = m as THREE.MeshPhysicalMaterial;
        if (pm && "transmission" in pm) pm.transmission = 0;
      }
    });
    // the loader root carries its own Z-up -> Y-up conversion: never touch its
    // transform, yaw an outer group instead (same parent frame as placement)
    const yaw = new THREE.Group();
    yaw.rotation.y = rotY;
    yaw.add(inner);
    const wrap = new THREE.Group();
    wrap.add(yaw);
    const box = new THREE.Box3().setFromObject(wrap);
    const size = box.getSize(new THREE.Vector3());
    wrap.scale.setScalar(normalize(size));
    // ground the model
    const box2 = new THREE.Box3().setFromObject(wrap);
    wrap.position.y -= box2.min.y;
    const size2 = box2.getSize(new THREE.Vector3());
    return { root: wrap, size: size2 };
  } finally {
    activeAsset = null;
  }
}

/**
 * Remaining packed prop (midrise building). Game convention for every loaded
 * model: nose/long axis aligned to local -z (see noseRotY per GLB above).
 */
/** Each asset pack's single saved state (from its availableStates). */
const ASSET_STATES: Record<string, string> = {
  midrise: "assembled",
};

const asLoaded = (m: GlbModel): LoadedModel => ({ root: m.root, size: m.size });

export async function loadGameAssets(
  preferredHero: HeroModelKey | undefined,
  onHeroLoaded?: (key: HeroModelKey, model: LoadedModel) => void
): Promise<GameAssets> {
  const mod = await loadAssetModule();
  const load = (key: string, rotY: number, norm: (s: THREE.Vector3) => number) =>
    loadModel(mod.assets, key, rotY, norm);
  // Start the selected hero alongside other assets instead of waiting for the
  // large building payload. Report each finished car immediately so gameplay
  // can replace the placeholder without waiting for every unused vehicle.
  const midrisePromise = load("midrise", 0, (s) => 26 / s.y);
  const heroEntries = Object.entries(HERO_GLBS) as [HeroModelKey, (typeof HERO_GLBS)[HeroModelKey]][];
  const loadHero = async ([key, cfg]: [HeroModelKey, (typeof HERO_GLBS)[HeroModelKey]]) => {
    const model = asLoaded(await loadGlbModel(cfg.url, {
      noseRotY: cfg.noseRotY,
      targetLength: cfg.len,
      // These AI assets are single merged meshes. Heuristic wheel carving
      // split the tire surface into orbiting fragments; keep the authored
      // complete wheel geometry intact.
      bodyPaint: true,
    }));
    onHeroLoaded?.(key, model);
    return [key, model] as const;
  };
  const preferredEntry = heroEntries.find(([key]) => key === preferredHero);
  const preferredPromise = preferredEntry ? loadHero(preferredEntry) : Promise.resolve(null);
  // Start other cars after the selected one finishes, so their downloads and
  // geometry parsing cannot delay the vehicle currently on screen.
  const remainingHeroesPromise = preferredPromise.then(() =>
    Promise.all(heroEntries.filter(([key]) => key !== preferredHero).map(loadHero))
  );
  const trafficPromise = Promise.all(
    TRAFFIC_GLBS.map((cfg) => loadGlbModel(cfg.url, { noseRotY: cfg.noseRotY, targetLength: cfg.len }))
  ).then((models) => models.map(asLoaded));
  const policePromise = loadGlbModel(policeGlbUrl, { noseRotY: 0, targetLength: 4.9 }).then(asLoaded);

  const [midrise, preferred, remainingHeroes, traffic, police] = await Promise.all([
    midrisePromise,
    preferredPromise,
    remainingHeroesPromise,
    trafficPromise,
    policePromise,
  ]);
  const hero = Object.fromEntries([
    ...(preferred ? [preferred] : []),
    ...remainingHeroes,
  ]) as Partial<Record<HeroModelKey, LoadedModel>>;
  return { traffic, police, midrise, hero };
}
