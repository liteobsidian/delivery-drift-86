import coupePackUrl from "../assets/vehicles/coupe/pack-1.bin.gz.b64?url";
import policeAssetSrc from "../assets/vehicles/police/asset.js?raw";
import policeOrientSrc from "../assets/vehicles/police/orientation.js?raw";
import policeDataUrl from "../assets/vehicles/police/data.json.gz.b64?url";
