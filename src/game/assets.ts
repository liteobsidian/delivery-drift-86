import hatchOrientSrc from "../assets/vehicles/hatchback/orientation.js?raw";
import hatchDataUrl from "../assets/vehicles/hatchback/data.json.gz.b64?url";
import hatchPackUrl from "../assets/vehicles/hatchback/pack-1.bin.gz.b64?url";
import sedanAssetSrc from "../assets/vehicles/sedan/asset.js?raw";
import sedanOrientSrc from "../assets/vehicles/sedan/orientation.js?raw";
import sedanDataUrl from "../assets/vehicles/sedan/data.json.gz.b64?url";
import sedanPackUrl from "../assets/vehicles/sedan/pack-1.bin.gz.b64?url";
import coupeAssetSrc from "../assets/vehicles/coupe/asset.js?raw";
import coupeOrientSrc from "../assets/vehicles/coupe/orientation.js?raw";
